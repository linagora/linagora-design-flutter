/// Spacing on the MUI 8 px grid used by @linagora/twake-mui 19.7.0
/// (`makeTheme.js` sets no `spacing`) and @linagora/twake-css 1.2.1.
abstract final class TwakeUiSpacing {
  static const double unit = 8;
  static const double xs = unit;
  static const double s = unit * 2;
  static const double m = unit * 3;
  static const double l = unit * 4;
  static const double xl = unit * 6;
  static const double xxl = unit * 8;
  static const double xxxl = unit * 12;
}
